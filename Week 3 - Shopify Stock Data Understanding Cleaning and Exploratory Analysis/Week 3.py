import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv("/content/drive/MyDrive/Colab Notebooks/AAPL.csv")
df

print(df.head())

print(df.shape)

print(df.info())

print(df.describe())

df["Date"] = pd.to_datetime(df["Date"], utc=True)
df['Date'].dtype

print(df.isnull().sum())

highest_price_record = df['Adj Close'].max()
display(highest_price_record)

lowest_price_record = df['Adj Close'].min()
display(lowest_price_record)

average_open_price = df['Open'].mean()
average_close_price = df['Close'].mean()

print(f"Average Opening Price: {average_open_price:.2f}")
print(f"Average Closing Price: {average_close_price:.2f}")

df = df.sort_values("Date")
df["Daily_Delta"] = df["Close"] - df["Open"]
df

# Sort descending by Daily_Delta, take the top 10
top10_gains = df.sort_values("Daily_Delta", ascending=False).head(10)
display(top10_gains)

df["Daily_Return"] = ((df["Close"] - df["Open"]) / df["Open"]) * 100
df

# Sort descending by Daily_Return, take the top 10 loesses
top10_losses = df.sort_values("Daily_Return", ascending=True).head(10)
display(top10_losses)

average_volume = df["Volume"].mean()
maximum_volume = df["Volume"].max()
minimum_volume = df["Volume"].min()

print("Average Volume:", average_volume)
print("Maximum Volume:", maximum_volume)
print("Minimum Volume:", minimum_volume)

threshold = 2 * average_volume
anomalous_days = df[df["Volume"] > threshold]
print("\nAnomalous Trading Days:\n")
print(anomalous_days[["Date", "Open", "Close", "Daily_Delta", "Daily_Return", "Volume"]])

mean_return = df["Daily_Return"].mean()
print(f"Mean: {mean_return}")

variance_return = df["Daily_Return"].var()
print(f"Variance: {variance_return}")

std_return = df["Daily_Return"].std()
print(f"Standard Deviation: {std_return}")