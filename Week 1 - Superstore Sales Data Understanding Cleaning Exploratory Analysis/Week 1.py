import pandas as pd
import numpy as np

import matplotlib.pyplot as plt
import seaborn as sns

"""### Loading the Dataset"""

df = pd.read_csv("/content/drive/MyDrive/Colab Notebooks/samplesuperstore.csv")

from google.colab import drive
